#!/usr/bin/env python3
"""Print the CORPUS-CONTRACT.md admission checklist for one factory-fetched dataset.

WHAT THIS DOES AND DOES NOT DO
This is a read-only gate, not a fetcher and not a corpus mutator. It reads one dataset
factory `provenance.json` (see program/datasets/README.md `S2`) plus a target CSD region
name, and prints five checks: licence tier vs. the region's already-declared tier,
provenance-group share against CORPUS-CONTRACT.md's B1 (<= 0.40 post-admission),
`verification_status == VERIFIED`, (check 4) a second, independent read of the full
catalogue row's own structural refusal signals, and (check 5) whether `provenance.json`'s
own `admission` block (`policy_version` and `constants`, once the factory writes one)
agrees with this tool's pinned policy constants. It does not touch CORPUS-CONTRACT.md,
csd-regions.json,
or any region's fetch list -- admitting a dataset for real is a human/agent action taken
after reading this tool's output, same discipline as csd-corpus-expand.py's structural
REFUSE gate (no override flag) but advisory rather than fetch-blocking, because this tool
runs after the fetch, not during it.

TASK A COORDINATION (round-3 review, closing check 5's structural-drift defect)
`ADAPTER_POLICY_CONSTANTS` below is not hand-transcribed. It is the exact key set and
values of `dataset_factory.admission.admission_constants()` as the factory COMMITS them,
`ADMISSION_POLICY_VERSION` included as a MEMBER of the dict rather than a sibling of it.
Hand-transcription is what produced the defect: this tool once pinned six lower_snake
keys against the factory's fourteen UPPER_SNAKE ones (key overlap: zero) and a
differently-punctuated version string, so `constants != ADAPTER_POLICY_CONSTANTS` failed
on every real record and check 5 refused every landed dataset with a constant, contentless
refusal. An intermediate fix closed the vocabulary half but kept the version outside the
dict, which still failed by exactly one key once the factory landed it inside; this is
the reconciled state, verified against a record the committed factory actually writes.

`tests/fixtures/dataset-factory-policy.json` is now GENERATED by the factory itself --
`dataset-factory policy-constants --out <path>` -- rather than transcribed, so the pinned
fixture is literally factory output. The command exists for this purpose; regenerate,
never edit by hand, and re-verify `ADAPTER_POLICY_CONSTANTS` against the regenerated file
(`test_adapter_policy_constants_match_pinned_fixture` fails if you forget).
`test_pinned_fixture_matches_live_factory_output_when_available` additionally re-imports
the real factory module (skipping when the sibling `dataset-factory` checkout is absent)
and requires FULL equality with `admission_constants()`, not a subset: a key the factory
has ADDED that this tool does not pin is precisely how the version key slipped through
once already, so it now fails rather than being tolerated. `check_policy_constants_drift`
(check 5) stays forward-compatible in the one direction that is safe: it PASSES with a
note when `provenance.json` carries no `admission` block at all (a record fetched before
the factory started emitting one), and only FAILs on an observable drift -- a
present-but-disagreeing `admission.policy_version`, a record whose two copies of the
version disagree with each other, and/or a differing `admission.constants`.

WHY THE LICENCE-TIER TABLE IS DUPLICATED HERE, NOT IMPORTED
scripts/csd-publish-checkpoint.py's LICENCE_TIER is the source of truth for what a region
is licensed under today. Importing it would couple this admission tool to the publish
script's module surface (and its torch/HF-hub-adjacent import chain) for the sake of one
small dict. The table is small, dated, and rarely changes; it is transcribed here with a
test (test_licence_tier_matches_publish_checkpoint) that fails loudly the day the two
tables disagree, which is a cheaper and more honest coupling than an import that pulls in
unrelated machinery for four rows.

CHECK 4 IS A SECOND, INDEPENDENT LOOK -- NOT A RE-READ OF THE SAME FIELDS
Checks 1-3 read only what the factory's `provenance.json` actually emits per dataset
(verdict, verification_status, provenance_group, total_bytes/file_count/file_manifest,
licence_* and a trimmed `catalogue_entry`). That trimmed entry carries `grant_scope` but
NOT `redistribute{nc,sa,nd,attribution}`, `provenance_red_flags`, or
`enrichment_licence_result` -- confirmed by reading every real provenance.json under
/mnt/bulk/csd-corpus/factory-2026-09-03/ (2026-09-03 ground pass), all of which trim
`catalogue_entry` to the same six keys. Those three fields only exist in the full
catalogue row (`docs/design/datasets/catalogue-2026-09-03.json`, keyed by `repo_id`), which
is also where the factory's OWN gate (`admission.check_admission`) failed to read them
(ground-pass findings B1-B3: narrativeqa and BeIR/cqadupstack both landed on /bulk despite
carrying a structural refusal in exactly these fields). Check 4 therefore loads that
catalogue independently and applies its own refusal logic against it, so a defect in the
factory's gate does not silently pass through this one too -- two gates reading two
different sources of truth, not one gate re-reading the same file.
"""

